import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, relative, resolve, sep } from "node:path";

const DIST_DIR = resolve("dist");
const OUTPUT_FILE = resolve("worker/static-assets.generated.ts");
const CONTENT_TYPES = {
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".webmanifest": "application/manifest+json; charset=utf-8",
};

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === "server" || entry.name === ".openai") continue;
    if (entry.name === "og.png") continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await filesIn(path)));
    if (entry.isFile()) files.push(path);
  }
  return files;
}

const assets = {};
for (const path of await filesIn(DIST_DIR)) {
  const urlPath = `/${relative(DIST_DIR, path).split(sep).join("/")}`;
  assets[urlPath] = {
    body: (await readFile(path)).toString("base64"),
    contentType: CONTENT_TYPES[extname(path).toLowerCase()] || "application/octet-stream",
  };
}

const source = `// Generated by scripts/generate-worker-assets.mjs. Do not edit manually.\n` +
  `export const STATIC_ASSETS = ${JSON.stringify(assets)} as const;\n`;
await writeFile(OUTPUT_FILE, source);
console.log(`Embedded ${Object.keys(assets).length} static files in ${OUTPUT_FILE}.`);
